
import React, { useState, useTransition } from 'react';
import { Loader2 } from 'lucide-react';
import { useAppDispatch } from '../../../app/hooks';
import { addNotification } from '../../ui/uiSlice';
import { createPermissionAction } from '../../../actions/rbacActions';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import {
    Dialog,
    DialogBody,
    DialogContent,
    DialogDescription,
    DialogFooter,
    DialogHeader,
    DialogTitle,
} from '@/components/ui/dialog';

interface PermissionModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSuccess: () => void;
}

const PermissionModal: React.FC<PermissionModalProps> = ({ isOpen, onClose, onSuccess }) => {
  const [name, setName] = useState('');
  const [isPending, startTransition] = useTransition();
  const dispatch = useAppDispatch();

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    startTransition(async () => {
        const response = await createPermissionAction({ name });
        if (response.success) {
            dispatch(addNotification({ type: 'success', message: 'Permission created successfully.' }));
            setName('');
            onSuccess();
            onClose();
        } else {
            dispatch(addNotification({ type: 'error', message: response.error || 'Failed.' }));
        }
    });
  };

  return (
    <Dialog
        open={isOpen}
        onOpenChange={(open) => {
            if (!open && !isPending) onClose();
        }}
    >
        <DialogContent className="sm:max-w-md">
            <DialogHeader>
                <DialogTitle>Create New Permission</DialogTitle>
                <DialogDescription>The machine name will be auto-generated by the backend.</DialogDescription>
            </DialogHeader>

            <DialogBody>
              <form id="perm-form" onSubmit={handleSubmit} className="grid gap-2">
                <Label htmlFor="perm-name">Permission Name</Label>
                <Input
                    id="perm-name"
                    value={name}
                    onChange={e => setName(e.target.value)}
                    placeholder="e.g. Delete Reports"
                    autoComplete="off"
                    required
                />
              </form>
            </DialogBody>

            <DialogFooter>
                <Button variant="outline" onClick={onClose} disabled={isPending}>
                    Cancel
                </Button>
                <Button type="submit" form="perm-form" disabled={isPending}>
                    {isPending && <Loader2 className="size-4 animate-spin" aria-hidden="true" />}
                    Create
                </Button>
            </DialogFooter>
        </DialogContent>
    </Dialog>
  );
};

export default PermissionModal;
