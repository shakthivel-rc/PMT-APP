/**
 * Generates the per-theme CSS custom-property blocks in `src/index.css` from the palette
 * data in `src/features/ui/themes.ts`.
 *
 * Ten themes times ~48 tokens is far too much to hand-author without mistakes, and most of
 * those tokens are not real decisions — a `-subtle` fill is always its accent mixed into
 * the surface, and a status foreground is always whichever of black/white actually passes
 * contrast. So the palette declares the ~20 values that matter and this derives the rest.
 *
 * Run:  node scripts/generate-theme-css.mjs
 * It rewrites the region between the BEGIN/END markers in src/index.css, in place.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const CSS_PATH = resolve(HERE, '../src/index.css');
const THEMES_PATH = resolve(HERE, '../src/features/ui/themes.ts');

const BEGIN = '/* THEME-BLOCKS:BEGIN — generated by scripts/generate-theme-css.mjs; edit themes.ts instead */';
const END = '/* THEME-BLOCKS:END */';

// ---------------------------------------------------------------- colour maths

const hexToRgb = (hex) => {
  const value = hex.replace('#', '');
  const full = value.length === 3 ? [...value].map((c) => c + c).join('') : value;
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
};

const rgbToHex = (rgb) => '#' + rgb.map((c) => Math.round(c).toString(16).padStart(2, '0')).join('');

/** Relative luminance per WCAG 2.x. */
const luminance = (hex) => {
  const [r, g, b] = hexToRgb(hex).map((channel) => {
    const s = channel / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

export const contrast = (a, b) => {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
};

/** Blend `amount` of `top` over `bottom`, both opaque hex. */
const mix = (top, bottom, amount) => {
  const t = hexToRgb(top);
  const b = hexToRgb(bottom);
  return rgbToHex(t.map((channel, i) => channel * amount + b[i] * (1 - amount)));
};

/**
 * Text colour for a filled accent: whichever of near-black / near-white reads better.
 * Picking by contrast rather than by theme mode matters — a pale accent like Nord's frost
 * or Dracula's green needs dark text even though the theme itself is dark.
 */
const onColor = (accent) => {
  const dark = '#0b0f17';
  const light = '#ffffff';
  return contrast(accent, dark) >= contrast(accent, light) ? dark : light;
};

/** A tinted fill for status banners: the accent, barely present, over the card surface. */
const subtle = (accent, surface, mode) => mix(accent, surface, mode === 'dark' ? 0.16 : 0.12);

/**
 * Nudge a colour until it clears `target` contrast against every surface it is drawn on.
 *
 * The published palettes are designed for syntax highlighting, where an accent only ever
 * sits on the editor background. Here the same accents carry small UI text on three
 * different surfaces, and several of them miss AA — Catppuccin Latte's green reads 2.6:1
 * on its own tint, Nord's red 2.2:1. Rather than hand-editing ten palettes and losing
 * their provenance, this walks the colour toward black (light themes) or white (dark
 * themes) in small steps and stops the moment it passes, so the hue stays recognisable.
 */
const ensureContrast = (color, backgrounds, mode, target = 4.5) => {
  const towards = mode === 'dark' ? '#ffffff' : '#000000';
  let candidate = color;
  for (let step = 0; step <= 20; step += 1) {
    if (backgrounds.every((bg) => contrast(candidate, bg) >= target)) return candidate;
    candidate = mix(towards, color, step * 0.04);
  }
  return candidate;
};

// ---------------------------------------------------------------- palette parsing

/** Reads the THEMES array out of the TS source without needing a TS toolchain. */
const readThemes = () => {
  const source = readFileSync(THEMES_PATH, 'utf8');
  const start = source.indexOf('export const THEMES');
  const end = source.indexOf('\n];', start);
  const body = source.slice(start, end);

  const themes = [];
  const entryPattern = /\{\s*\n\s*id: '([^']+)',\s*\n\s*name: '([^']*)',\s*\n\s*mode: '(light|dark)',/g;
  let match;
  while ((match = entryPattern.exec(body))) {
    const [, id, name, mode] = match;
    const paletteStart = body.indexOf('palette: {', match.index);
    const paletteEnd = body.indexOf('},', paletteStart);
    const paletteBody = body.slice(paletteStart, paletteEnd);
    const palette = {};
    for (const [, key, value] of paletteBody.matchAll(/(\w+): '([^']+)'/g)) palette[key] = value;
    themes.push({ id, name, mode, palette });
  }
  return themes;
};

// ---------------------------------------------------------------- token derivation

const tokensFor = ({ mode, palette: p }) => {
  const isDark = mode === 'dark';
  // Popovers sit above cards, so they lift one step further from the page.
  const popover = isDark ? mix('#ffffff', p.surface, 0.05) : p.surface;
  const muted = isDark ? p.surface : p.surfaceAlt;
  const shadow = (y, blur, alpha) => `0 ${y}px ${blur}px rgba(${p.shadowRgb}, ${alpha})`;

  // Subtle fills keep the ORIGINAL accent so the tint stays true to the palette; the
  // accent itself is then adjusted for legibility on the three surfaces it is drawn on.
  const fills = {
    success: subtle(p.success, p.surface, mode),
    warning: subtle(p.warning, p.surface, mode),
    danger: subtle(p.danger, p.surface, mode),
    info: subtle(p.info, p.surface, mode),
  };
  const readable = (accent, fill) =>
    ensureContrast(accent, [fill, p.surface, p.background], mode);

  const success = readable(p.success, fills.success);
  const warning = readable(p.warning, fills.warning);
  const danger = readable(p.danger, fills.danger);
  const info = readable(p.info, fills.info);
  const mutedForeground = ensureContrast(p.mutedForeground, [p.background, p.surface, muted], mode);

  return {
    '--background': p.background,
    '--foreground': p.foreground,
    '--card': p.surface,
    '--card-foreground': p.foreground,
    '--popover': popover,
    '--popover-foreground': p.foreground,

    '--primary': p.primary,
    '--primary-foreground': onColor(p.primary),
    '--secondary': p.surfaceAlt,
    '--secondary-foreground': p.foreground,
    '--muted': muted,
    '--muted-foreground': mutedForeground,
    '--accent': p.surfaceAlt,
    '--accent-foreground': p.foreground,

    '--destructive': danger,
    '--destructive-foreground': onColor(danger),

    // Walked to 3:1 like any other non-text contrast. Every text input and select trigger
    // in this app is `bg-transparent`, so the 1px border is the ONLY thing indicating a
    // control exists — which makes it the "visual boundary" WCAG 2.2 SC 1.4.11 requires
    // 3:1 for. Nine of ten themes missed it, the default light theme worst at 1.13:1: a
    // low-vision user saw a label with no field under it. `--border` has to clear both
    // surfaces it is drawn on; `--input` sits on cards.
    '--border': ensureContrast(p.border, [p.background, p.surface], mode, 3),
    '--input': ensureContrast(p.input, [p.surface, p.background], mode, 3),
    '--ring': p.ring,

    '--success': success,
    '--success-foreground': onColor(success),
    '--success-subtle': fills.success,
    '--warning': warning,
    '--warning-foreground': onColor(warning),
    '--warning-subtle': fills.warning,
    '--info': info,
    '--info-foreground': onColor(info),
    '--info-subtle': fills.info,
    '--danger': danger,
    '--danger-foreground': onColor(danger),
    '--danger-subtle': fills.danger,

    // Categorical ramp — the theme's own accents, so charts never clash with the UI.
    '--chart-1': p.primary,
    '--chart-2': info,
    '--chart-3': success,
    '--chart-4': warning,
    '--chart-5': danger,

    // The sidebar has its OWN background, and these foregrounds were derived against the
    // page surfaces only — `--sidebar-foreground` reused `mutedForeground`, which is walked
    // against background/surface/muted and never against `--sidebar`. A rendered scan
    // caught nav labels failing 4.5:1 on the dark palettes for exactly that reason.
    '--sidebar': p.sidebar,
    '--sidebar-foreground': ensureContrast(p.mutedForeground, [p.sidebar, p.background], mode),
    '--sidebar-primary': p.primary,
    '--sidebar-primary-foreground': onColor(p.primary),
    '--sidebar-accent': p.surfaceAlt,
    '--sidebar-accent-foreground': ensureContrast(p.foreground, [p.sidebar, p.surfaceAlt], mode),
    '--sidebar-border': p.border,
    '--sidebar-ring': p.ring,

    '--shadow-xs': shadow(1, 2, isDark ? 0.4 : 0.06),
    '--shadow-sm': shadow(2, 6, isDark ? 0.45 : 0.1),
    '--shadow-md': shadow(6, 16, isDark ? 0.5 : 0.12),
    '--shadow-lg': shadow(16, 40, isDark ? 0.6 : 0.18),
    '--shadow-primary': `0 4px 14px rgba(${hexToRgb(p.primary).join(', ')}, ${isDark ? 0.35 : 0.3})`,

    'color-scheme': mode,
  };
};

// ---------------------------------------------------------------- emit

const block = (theme) => {
  const selector =
    theme.id === 'light'
      ? // The default theme is also the fallback for an unknown/absent data-theme.
        ":root,\n[data-theme='light']"
      : `[data-theme='${theme.id}']`;
  const tokens = tokensFor(theme);
  const lines = Object.entries(tokens).map(([key, value]) => `  ${key}: ${value};`);
  return `${selector} {\n  --radius: 0.625rem;\n${lines.join('\n')}\n}`;
};

const main = () => {
  const themes = readThemes();
  if (themes.length === 0) throw new Error('No themes parsed from themes.ts');

  const generated = [
    BEGIN,
    '/* Palette values come from each theme\'s own published spec; see themes.ts for sources. */',
    ...themes.map(block),
    END,
  ].join('\n\n');

  const css = readFileSync(CSS_PATH, 'utf8');
  const beginAt = css.indexOf(BEGIN);
  const endAt = css.indexOf(END);
  if (beginAt === -1 || endAt === -1) throw new Error('Markers not found in index.css');

  writeFileSync(CSS_PATH, css.slice(0, beginAt) + generated + css.slice(endAt + END.length));
  console.log(`Wrote ${themes.length} theme blocks to src/index.css`);

  // Report the contrast pairs WCAG cares about, so a bad palette is caught at authoring
  // time rather than by a user. The Vitest suite asserts the same thing.
  for (const theme of themes) {
    const t = tokensFor(theme);
    const checks = [
      ['fg/bg', t['--foreground'], t['--background']],
      ['fg/card', t['--card-foreground'], t['--card']],
      ['muted/bg', t['--muted-foreground'], t['--background']],
      ['muted/card', t['--muted-foreground'], t['--card']],
      ['muted/muted', t['--muted-foreground'], t['--muted']],
      ['on-primary', t['--primary-foreground'], t['--primary']],
      ['success/subtle', t['--success'], t['--success-subtle']],
      ['warning/subtle', t['--warning'], t['--warning-subtle']],
      ['danger/subtle', t['--danger'], t['--danger-subtle']],
      ['info/subtle', t['--info'], t['--info-subtle']],
    ];
    const failures = checks
      .map(([label, a, b]) => [label, contrast(a, b)])
      .filter(([, ratio]) => ratio < 4.5)
      .map(([label, ratio]) => `${label}=${ratio.toFixed(2)}`);
    const ring = contrast(t['--ring'], t['--background']);
    if (ring < 3) failures.push(`ring/bg=${ring.toFixed(2)}`);
    console.log(`  ${theme.id.padEnd(20)} ${failures.length ? '⚠ ' + failures.join(' ') : 'ok'}`);
  }
};

main();
